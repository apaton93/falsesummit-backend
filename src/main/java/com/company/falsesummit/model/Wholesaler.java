package com.company.falsesummit.model;

public class Wholesaler {
    public int id;
    public String name;
    public String bundle;
    public String phone;
    public String emergency;
    public String email;

    public Wholesaler(int id, String name, String bundle, String phone, String emergency, String email) {
        this.id = id;
        this.name = name;
        this.bundle = bundle;
        this.phone = phone;
        this.emergency = emergency;
        this.email = email;
    }

}
